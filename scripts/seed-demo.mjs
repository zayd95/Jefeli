async function resetDemo() {
  const { data } = await admin.auth.admin.listUsers({ perPage: 1000 });
  for (const u of data?.users ?? []) {
    if (u.email?.endsWith(`@${DOMAIN}`)) {
      for (const bucket of ['avatars', 'public-media', 'private-media']) {
        const files = [];
        const walk = async (prefix) => {
          const { data: items } = await admin.storage.from(bucket).list(prefix, { limit: 1000 });
          for (const it of items ?? []) {
            const p = `${prefix}/${it.name}`;
            if (!it.id) await walk(p);
            else files.push(p);
          }
        };
        await walk(u.id);
        if (files.length) await admin.storage.from(bucket).remove(files);
      }
      await admin.auth.admin.deleteUser(u.id);
      console.log(`  removed ${u.email}`);
    }
  }
}

async function signIn(email) {
  const client = createClient(URL_, ANON, { auth: { persistSession: false, autoRefreshToken: false } });
  must(await client.auth.signInWithPassword({ email, password: PASSWORD }), `sign in ${email}`);
  const { data } = await client.auth.getUser();
  return { client, id: data.user.id };
}

async function upload(u, bucket, folder, buf) {
  const p = `${u.id}/${folder}/${crypto.randomUUID()}.jpg`;
  must(await u.client.storage.from(bucket).upload(p, buf, { contentType: 'image/jpeg', upsert: false }), `upload ${p}`);
  const meta = await sharp(buf).metadata();
  return { kind: 'image', path: p, width: meta.width, height: meta.height };
}

