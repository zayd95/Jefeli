// A fixture with less than this left is recreated, so a full test run never sees it expire.
const STATUS_MIN_VALIDITY_MS = 2 * 60 * 60 * 1000;

async function createStatusFixture(user, f, productId, buf) {
  const media = await upload(user, 'private-media', 'stories', buf);
  must(
    await user.client.rpc('create_story', { p_media_kind: 'image', p_path: media.path, p_poster_path: null, p_width: media.width, p_height: media.height, p_duration_ms: null, p_caption: f.caption, p_audience: f.audience, p_product_id: productId }),
    `story ${f.user}`,
  );
}

async function refreshStatusFixtures() {
  const refreshed = [];
  const minExpiry = new Date(Date.now() + STATUS_MIN_VALIDITY_MS).toISOString();
  for (const f of STATUS_FIXTURES) {
    const spec = USERS.find((x) => x.key === f.user);
    const user = { ...(await signIn(spec.email)), spec };
    const live = must(
      await admin.from('stories').select('id').eq('author_id', user.id).eq('caption', f.caption).is('deleted_at', null).gt('expires_at', minExpiry).limit(1),
      `stories of ${f.user}`,
    );
    if (live.length) continue;
    const product = must(await admin.from('products').select('id').eq('seller_id', user.id).eq('title', f.product).maybeSingle(), `product ${f.product}`);
    if (!product) continue; // the DÉMO set was edited by hand: leave it alone
    const buf = f.image === 'dress' ? await asset('yellow_dress.jpg', 800) : await crop(740, 330, 298, 258);
    await createStatusFixture(user, f, product.id, buf);
    refreshed.push(`${spec.name} (« ${f.caption} »)`);
  }
  return refreshed;
}

