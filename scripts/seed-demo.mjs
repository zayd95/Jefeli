async function crop(left, top, width, height, outW = 960) {
  return sharp(REF)
    .extract({ left, top, width, height })
    .resize({ width: outW, kernel: 'lanczos3' })
    .sharpen({ sigma: 0.8 })
    .jpeg({ quality: 84 })
    .toBuffer();
}
async function asset(name, outW = 900) {
  return sharp(path.join(ASSETS, name)).resize({ width: outW, kernel: 'lanczos3' }).sharpen({ sigma: 0.8 }).jpeg({ quality: 84 }).toBuffer();
}
async function wax(palette, seed) {
  const [bg, a, b, c] = palette;
  const cells = [];
  for (let y = 0; y < 6; y++) {
    for (let x = 0; x < 6; x++) {
      const cx = x * 180 + 90 + (y % 2) * 45;
      const cy = y * 180 + 90;
      const r = 54 + ((x * 7 + y * 3 + seed) % 4) * 6;
      cells.push(`<circle cx="${cx}" cy="${cy}" r="${r}" fill="${a}"/>`);
      cells.push(`<circle cx="${cx}" cy="${cy}" r="${r * 0.62}" fill="${bg}"/>`);
      cells.push(`<circle cx="${cx}" cy="${cy}" r="${r * 0.3}" fill="${b}"/>`);
      cells.push(`<path d="M ${cx - 88} ${cy + 88} q 44 -40 88 0 t 88 0" stroke="${c}" stroke-width="10" fill="none"/>`);
    }
  }
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="1080" height="1080"><rect width="1080" height="1080" fill="${bg}"/>${cells.join('')}</svg>`;
  return sharp(Buffer.from(svg)).jpeg({ quality: 86 }).toBuffer();
}

